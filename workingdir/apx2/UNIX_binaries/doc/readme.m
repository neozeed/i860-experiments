    3.0 DOCUMENTATION  

    A Note on i860 Math Library:
    ----------------------------

    This library is performance-oriented at the expense of a minor loss of
    accuracy. The loss of significant binary digits is around 3 units for 
    normal values; for boundary conditions accuracy may be insufficient for 
    applications requiring extremely precise results. 

    There are no error checks performed in this library in view of execution
    performance. If input values to any of the functions are beyond the 
    specified range, the results are undefined.

    This library is about 20% - 50% faster than the standard compiler math 
    functions, depending upon the input values and the functions called.  
    Computations which require higher accuracy should use the standard 
    libraries that go with the compiler.  Applications which need high
    performance should use this library.



