    Please note that the Math library contains single as well as double 
    precision implementations of the various functions (eg, cos and cosf). 
    The single precision versions of these functions as well as  complex 
    functions do not exist in the C library (libca.a). Also, the function 
    sincos (single and double precision version) is included only in the Math
    library. All other double precision functions (eg, cos, sin,...) are 
    duplicated in the C library as well as in the i860 Math library. 
    All functions in the i860 Math library, except sincos (single and double
    precision version) exist in the FORTRAN libraries.



